// ログインの単体テスト

// 入力バリデーション
// - メールアドレスが未入力の場合はsignInを呼ばない
// - パスワードが未入力の場合はsignInを呼ばない
// - メールアドレス形式が不正な場合はsignInを呼ばない
// - メールアドレス前後の空白を除去する
// - メールアドレスを小文字へ正規化する
// - パスワードは空白除去や小文字変換を行わない

// ログイン送信
// - 入力したメールアドレスをusernameとしてsignInへ渡す
// - 入力したパスワードをpasswordとしてsignInへ渡す
// - 1回の送信でsignInを1回だけ呼ぶ

// ログイン成功
// - isSignedIn: trueをログイン成功として扱う
// - ログイン成功時に/plansへ遷移する
// - ログイン成功時にエラーメッセージを表示しない

// ログイン失敗
// - パスワードが間違っている場合に共通エラーメッセージを表示する
// - ユーザーが存在しない場合に共通エラーメッセージを表示する
// - ユーザー不存在とパスワード間違いで同じメッセージを表示する
// - Cognitoとの通信に失敗した場合にエラーメッセージを表示する
// - ログイン失敗時に画面遷移しない
// - 再送信時に以前のエラーメッセージを消す

// 未完了の認証
// - isSignedIn: falseをログイン成功として扱わない
// - isSignedIn: falseの場合に画面遷移しない
// - isSignedIn: falseの場合に追加認証が必要なメッセージを表示する

// 送信状態
// - 認証処理中に「ログイン中...」を表示する
// - 認証処理中はログインボタンを無効にする
// - 認証処理中の連続クリックでsignInを二重に呼ばない
// - ログイン失敗後にログインボタンを再度有効にする
// - 未完了の認証後にログインボタンを再度有効にする

// セキュリティ
// - Cognitoから返された詳細なエラーを画面へそのまま表示しない
// - メールアドレスが存在するかどうかをエラーメッセージから判別できない
